// Writes dist/_redirects, mapping every old Blogger address onto its new page.
//
// The old site was Blogger, so every page and post lived at a path like
// /2019/04/happy-earth-day.html. Those addresses are in Google's index, in the
// school's own newsletters and on other people's websites. Without this they
// all become 404s the moment the domain points here.
//
// The mapping is not guessable: Blogger derived its slug from the title at the
// time of posting, and this site derives its own from the date plus the title.
// So it is read from the legacyUrl field the migration recorded on each entry.
//
// Runs after astro build, alongside write-headers.mjs.

import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "dist", "_redirects");

// Enough of a frontmatter read for fields this project writes itself.
function frontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};
  const out = {};
  for (const line of match[1].split(/\r?\n/)) {
    const hit = line.match(/^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/);
    if (!hit) continue;
    out[hit[1]] = hit[2].trim().replace(/^["'](.*)["']$/, "$1");
  }
  return out;
}

// Only the path matters. The old site was http on a domain that may yet
// change, and Pages matches on path.
function legacyPath(value) {
  try {
    return new URL(value).pathname;
  } catch {
    return value.startsWith("/") ? value : null;
  }
}

function collect(dir, toTarget) {
  const full = path.join(ROOT, dir);
  if (!fs.existsSync(full)) return [];

  return fs
    .readdirSync(full)
    .filter((name) => name.endsWith(".md"))
    .flatMap((name) => {
      const data = frontmatter(fs.readFileSync(path.join(full, name), "utf8"));
      if (!data.legacyUrl) return [];

      const from = legacyPath(data.legacyUrl);
      if (!from) return [];

      const slug = name.replace(/\.md$/, "");
      const target = toTarget(slug, data);
      return target ? [[from, target]] : [];
    });
}

const rules = [
  // A page that is only a menu link to another website builds no route of its
  // own, so its old address has to go to the site it points at.
  ...collect("content/pages", (slug, data) =>
    data.isLink === "true" ? data.linkUrl || null : `/${slug}/`
  ),
  ...collect("content/news", (slug) => `/news/${slug}/`),
];

const seen = new Set();
const lines = [];
for (const [from, to] of rules) {
  if (seen.has(from) || from === to) continue;
  seen.add(from);
  lines.push(`${from}  ${to}  301`);
}

lines.sort();

if (!fs.existsSync(path.dirname(OUT))) {
  console.warn("  [redirects] dist does not exist, skipping");
  process.exit(0);
}

const header = "# Old Blogger addresses. Generated by tools/write-redirects.mjs.\n";
fs.writeFileSync(OUT, header + lines.join("\n") + "\n");
console.log(`  [redirects] ${lines.length} old addresses mapped`);
